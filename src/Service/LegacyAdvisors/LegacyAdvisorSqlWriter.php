<?php

namespace App\Service\LegacyAdvisors;

use App\Entity\Ic\IcAdvisorType;

/**
 * Writes the legacy advisor import as SQL. Every statement is safe to run again: an advisor is
 * inserted only if its natural key isn't there yet, legacy_programs is set only while empty, and
 * links use INSERT IGNORE. Buildings, programs and advisors are found by name, never by id, so the
 * file runs the same on any copy of the database.
 */
final class LegacyAdvisorSqlWriter
{
    public const AUDIT_USER = 'legacy_import';

    private const COLUMNS = 'type, first_name, last_name, organization, email, phone, room, building_id, url, created, created_by, updated, updated_by';

    public function write(LegacyImportResult $result, string $source): string
    {
        $user = $this->quote(self::AUDIT_USER);
        $buildingNames = array_values(array_unique(array_filter(array_map(
            fn (LegacyAdvisor $advisor) => $advisor->buildingName,
            $result->advisors
        ))));
        sort($buildingNames);
        $withBuilding = count(array_filter($result->advisors, fn (LegacyAdvisor $advisor) => $advisor->buildingName !== null));

        $lines = [
            '-- Legacy advisor import: ic_advisors and program_advisor from advisor_programs and uacdc_advisor_programs.',
            '-- Generated by app:advisors:legacy-sql on ' . date('Y-m-d H:i') . '.',
            '-- Source: ' . $source,
            sprintf('-- Expected: %d advisors, %d links, %d with a building', count($result->advisors), $result->linkCount(), $withBuilding),
            '-- Safe to re-run: existing advisors are matched by name (and email), links use INSERT IGNORE.',
            '-- Run after migrating (Version20261125000000 adds legacy_programs), with a backup:',
            '--   mariadb ic < sql/legacy_advisors_import.sql',
            '-- The checks at the end should match the Expected line, missing_building should return no rows, and',
            '-- the legacy tables should still have the row counts and last updates in the Source line.',
            '',
            'SET NAMES utf8mb4;',
            'START TRANSACTION;',
        ];

        foreach ($result->advisors as $advisor) {
            $key = $this->naturalKey($advisor);
            $lines[] = '';
            $lines[] = '-- ' . $advisor->key;
            $lines[] = 'INSERT INTO ic_advisors (' . self::COLUMNS . ")\n"
                . 'SELECT ' . implode(', ', [
                    $this->quote($advisor->type->value),
                    $this->quote($advisor->firstName),
                    $this->quote($advisor->lastName),
                    $this->quote($advisor->organization),
                    $this->quote($advisor->email),
                    $this->quote($advisor->phone),
                    $this->quote($advisor->room),
                    $advisor->buildingName === null
                        ? 'NULL'
                        : "(SELECT id FROM map_item WHERE discr = 'building' AND name = " . $this->quote($advisor->buildingName) . ')',
                    $this->quote($advisor->url),
                    'NOW()', $user, 'NOW()', $user,
                ]) . "\n"
                . "FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM ic_advisors WHERE $key);";
            $lines[] = "SET @advisor = (SELECT id FROM ic_advisors WHERE $key ORDER BY id LIMIT 1);";

            if ($advisor->legacyPrograms) {
                $lines[] = 'UPDATE ic_advisors SET legacy_programs = ' . $this->quote($advisor->legacyProgramsText())
                    . ' WHERE id = @advisor AND legacy_programs IS NULL;';
            }

            if ($advisor->programs) {
                $pairs = array_map(
                    fn (array $program) => '(' . $this->quote($program[0]) . ', ' . $this->quote($program[1]) . ')',
                    $advisor->programs
                );
                $lines[] = "INSERT IGNORE INTO program_advisor (program_id, advisor_id)\n"
                    . 'SELECT p.id, @advisor FROM program_programs p WHERE (TRIM(p.full_name), p.catalog) IN (' . implode(', ', $pairs) . ');';
            }
        }

        $lines[] = '';
        $lines[] = 'COMMIT;';
        $lines[] = '';
        $lines[] = "SELECT COUNT(*) AS imported_advisors FROM ic_advisors WHERE created_by = $user;";
        $lines[] = 'SELECT COUNT(*) AS imported_links FROM program_advisor l JOIN ic_advisors a ON a.id = l.advisor_id'
            . " WHERE a.created_by = $user;";
        $lines[] = "SELECT COUNT(*) AS imported_with_building FROM ic_advisors WHERE created_by = $user AND building_id IS NOT NULL;";
        if ($buildingNames) {
            $names = implode(' UNION ALL ', array_map(
                fn (string $name, int $i) => 'SELECT ' . $this->quote($name) . ($i === 0 ? ' AS name' : ''),
                $buildingNames,
                array_keys($buildingNames)
            ));
            $lines[] = "SELECT b.name AS missing_building FROM ($names) b\n"
                . "WHERE NOT EXISTS (SELECT 1 FROM map_item m WHERE m.discr = 'building' AND m.name = b.name);";
        }
        $lines[] = "SELECT 'advisor_programs' AS legacy_table, COUNT(*) AS row_count, MAX(updated_at) AS last_updated FROM advisor_programs\n"
            . "UNION ALL SELECT 'uacdc_advisor_programs', COUNT(*), MAX(updated_at) FROM uacdc_advisor_programs;";

        return implode("\n", $lines) . "\n";
    }

    /**
     * How an advisor is recognized: a person by last name and email (first name without an
     * email), an organization by its name.
     */
    private function naturalKey(LegacyAdvisor $advisor): string
    {
        if ($advisor->type === IcAdvisorType::ORGANIZATION) {
            return "type = 'Organization' AND organization = " . $this->quote($advisor->organization);
        }

        $key = "type = 'Person' AND last_name = " . $this->quote($advisor->lastName);

        return $advisor->email === null
            ? $key . ' AND first_name = ' . $this->quote($advisor->firstName)
            : $key . ' AND email <=> ' . $this->quote($advisor->email);
    }

    private function quote(?string $value): string
    {
        if ($value === null) {
            return 'NULL';
        }

        return "'" . str_replace(['\\', "'"], ['\\\\', "''"], $value) . "'";
    }
}
